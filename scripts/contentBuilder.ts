import { mkdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { compile } from '@mdx-js/mdx';
import rehypeMdxCodeProps from 'rehype-mdx-code-props';
import studio from '../studio';
import { Mark } from '../src/lib/markdown';
import { rehypeHighlightCode } from './rehypeHighlightCode';

const outputDirectory = path.resolve('src/generated/content');
const generatedHeader = '// Generated by scripts/contentBuilder.ts. Do not edit.\n';

async function buildContent() {
	const markdown = new Mark();
	const metadata: Record<string, unknown[]> = {};
	const files = new Map<string, string>();
	const collections: string[] = [];
	let count = 0;

	// Studio and Markdown parsing are build-only. Never import runtime repositories
	// here: they consume this script's generated output.
	for (const collection of studio._.collections) {
		if (collection.skip) continue;
		const entries = await collection.getEntries();
		entries.sort((a, b) => a.slug.localeCompare(b.slug));
		metadata[collection.name] = [];
		const modules: string[] = [];

		for (const entry of entries) {
			if ('hidden' in entry.metadata && entry.metadata.hidden) continue;
			try {
				const validation = await collection._metadataSchema?.['~standard'].validate(entry.metadata);
				if (validation?.issues) {
					throw new Error(`Invalid front matter: ${JSON.stringify(validation.issues)}`);
				}
				const compiled = await compile({ path: entry.path, value: entry.content }, {
					format: 'mdx',
					outputFormat: 'program',
					development: false,
					rehypePlugins: [rehypeHighlightCode, rehypeMdxCodeProps],
				});
				const modulePath = `${collection.name}/${entry.slug}.js`;
				count++;
				files.set(modulePath, generatedHeader + String(compiled));
				modules.push(`\t\t${JSON.stringify(entry.slug)}: () => import(${JSON.stringify(`./${modulePath}`)}),`);
				metadata[collection.name].push({
					slug: entry.slug,
					metadata: entry.metadata,
					content: entry.content,
					renderedContent: markdown.transform(entry.content),
					readTime: entry.readTime,
				});
			} catch (cause) {
				throw new Error(`Failed to generate ${collection.name}/${entry.slug}`, { cause });
			}
		}
		collections.push(`\t${JSON.stringify(collection.name)}: {\n${modules.join('\n')}\n\t},`);
	}

	files.set('metadata.server.ts', generatedHeader
		+ 'import type { ContentManifest } from "../../lib/content/types";\n\n'
		+ `export const content: ContentManifest = ${JSON.stringify(metadata, null, '\t')};\n`);
	files.set('modules.ts', [
		generatedHeader.trimEnd(),
		'import type { ComponentType } from "react";',
		'import type { MDXComponents } from "mdx/types.js";',
		'import type { ContentCollection } from "../../lib/content/types";',
		'',
		'type ContentModule = { default: ComponentType<{ components?: MDXComponents }> };',
		'export const contentModules: Record<ContentCollection, Record<string, () => Promise<ContentModule>>> = {',
		...collections,
		'};\n',
	].join('\n'));

	// Replace output only after every document has compiled successfully, and remove
	// stale modules for hidden, deleted or renamed source entries.
	await rm(outputDirectory, { recursive: true, force: true });
	for (const [name, contents] of files) {
		const destination = path.join(outputDirectory, name);
		await mkdir(path.dirname(destination), { recursive: true });
		await writeFile(destination, contents);
	}
	console.log(`Generated ${count} content modules in ${path.relative(process.cwd(), outputDirectory)}.`);
}

await buildContent();
